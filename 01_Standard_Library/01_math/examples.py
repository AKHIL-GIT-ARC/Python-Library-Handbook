import math

print("PI:", math.pi)
print("Euler:", math.e)
print("Square Root:", math.sqrt(25))
print("Power:", math.pow(2, 5))
print("Ceil:", math.ceil(5.2))
print("Floor:", math.floor(5.8))
print("Factorial:", math.factorial(5))
print("GCD:", math.gcd(20, 30))
print("LCM:", math.lcm(20, 30))
print("Sin(90):", math.sin(math.radians(90)))